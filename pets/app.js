  // dpRunQuery — samples Laplace noise and updates the bar chart and stats.
  // Exposed on window so the inline onclick can reach it.
  window.dpRunQuery = async function() {
    const myEpoch = renderEpoch;  // capture epoch — bail if module is switched mid-animation
    if (queryRunning) return;
    queryRunning = true;
    $('dp-run-btn').disabled = true;
    const steps = ['dp-s1','dp-s2','dp-s3','dp-s4'];

    try {
    // Animate through each step sequentially
    for (let i = 0; i < steps.length; i++) {
      steps.forEach((s, j) => {
        $(s).className = 'step' + (j < i ? ' done' : j === i ? ' active' : '');
      });
      await sleepOrBail(600, myEpoch);
    }

    // Laplace noise via inverse-CDF method: noise = −b·sign(u)·ln(1−2|u|), b = sensitivity/ε
    const scale = 1 / epsilon;
    lastNoisy = trueVals.map(v => {
      const u = Math.random() - 0.5;
      const noise = -scale * Math.sign(u) * Math.log(1 - 2 * Math.abs(u));
      return Math.max(0, Math.round(v + noise));
    });
    dpDrawBars(trueVals, lastNoisy, labels);

    // Compute per-run error stats and update the dynamic tooltip body
    const avgErr = lastNoisy.reduce((s, v, i) => s + Math.abs(v - trueVals[i]), 0) / lastNoisy.length;
    $('dp-error').textContent = `±${avgErr.toFixed(1)} students`;
    const worstIdx  = lastNoisy.reduce((b, v, i) => Math.abs(v-trueVals[i]) > Math.abs(lastNoisy[b]-trueVals[b]) ? i : b, 0);
    const bestIdx   = lastNoisy.reduce((b, v, i) => Math.abs(v-trueVals[i]) < Math.abs(lastNoisy[b]-trueVals[b]) ? i : b, 0);
    const worstDiff = Math.abs(lastNoisy[worstIdx] - trueVals[worstIdx]);
    const worstDir  = lastNoisy[worstIdx] > trueVals[worstIdx] ? 'overcounted' : 'undercounted';
    const bestDiff  = Math.abs(lastNoisy[bestIdx]  - trueVals[bestIdx]);
    const pctErr    = ((avgErr / (trueVals.reduce((s,v)=>s+v,0)/trueVals.length)) * 100).toFixed(1);
    const qual      = avgErr < 5 ? 'negligible for most policy decisions'
                    : avgErr < 15 ? 'moderate — usable for trends but not precise headcounts'
                    : avgErr < 30 ? 'significant — directional signals only'
                    : 'large — interpret with caution';
    TIPS['avg-abs-error'].body =
      `Each reported count is off by ~${avgErr.toFixed(1)} students on average (${pctErr}% of typical group size). ` +
      `This run: worst was ${labels[worstIdx]} — true count ${trueVals[worstIdx]}, reported ${lastNoisy[worstIdx]} (${worstDir} by ${worstDiff}). ` +
      `Closest: ${labels[bestIdx]}, off by only ${bestDiff}. Overall: ${qual}. ` +
      `Run the query again to see noise vary — each run draws fresh Laplace values.`;

    // Accumulate privacy budget: sequential composition costs ε per query
    budgetSpent += epsilon;
    dpUpdateBudgetMeter();

    steps.forEach(s => { $(s).className = 'step done'; });
    queryRunning = false;
    // Keep button disabled if budget is now exhausted
    if (budgetSpent < budgetMax) $('dp-run-btn').disabled = false;
    } catch(e) { if (e !== BAIL) throw e; queryRunning = false; }
  };

  // dpUpdateBudgetMeter — repaints the budget bar, label, and button state.
  // Called after every query run and after a reset.
  function dpUpdateBudgetMeter() {
    const bar   = $('budget-bar');
    const label = $('budget-label');
    if (!bar || !label) return;
    const pct      = Math.min(1, budgetSpent / budgetMax);
    const colour   = pct >= 0.85 ? 'var(--coral)' : pct >= 0.5 ? 'var(--amber)' : 'var(--mint)';
    const exhausted = budgetSpent >= budgetMax;
    bar.style.width      = (pct * 100).toFixed(1) + '%';
    bar.style.background = colour;
    label.style.color    = colour;
    label.textContent    = exhausted
      ? `Budget exhausted (${budgetSpent.toFixed(1)} / ${budgetMax.toFixed(1)} ε) — reset to continue`
      : `Spent: ${budgetSpent.toFixed(1)} / ${budgetMax.toFixed(1)} ε`;
    const btn = $('dp-run-btn');
    if (btn) {
      btn.disabled    = exhausted;
      btn.textContent = exhausted ? '⛔ Budget exhausted' : '▶ Run Query';
    }
  }

  // dpResetBudget — zeroes accumulated spend and repaints the meter.
  window.dpResetBudget = function() {
    budgetSpent = 0;
    dpUpdateBudgetMeter();
  };

  // dpUpdateBudgetMax — updates the cap when the user edits the budget-cap input.
