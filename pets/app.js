      const line = c.nizkpLines[i];
      if (!line.text) { el.innerHTML += '<br>'; continue; }
      const text = line.text
        .replace('{hex32}', `<span style="color:var(--mint)">0x${zkpRandHex(32)}</span>`)
        .replace('{hex16}', `<span style="color:var(--blue)">0x${zkpRandHex(16)}</span>`)
        .replace('{hex24}', `<span style="color:var(--purple)">0x${zkpRandHex(24)}</span>`);
