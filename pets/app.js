/** Random float in [min, max) */
function rand(min, max) { return Math.random() * (max - min) + min; }

/** Random integer in [min, max] inclusive */
function randInt(min, max) { return Math.floor(rand(min, max + 1)); }

/** Promise-based delay for use in async animation sequences */
function sleep(ms) { return new Promise(r => setTimeout(r, ms)); }

/** Returns a debounced version of fn — invocation is delayed by ms milliseconds
 *  after the last call. Used to throttle the D3 bar-chart redraw on slider drag
 *  so it fires once per gesture rather than on every pixel of movement. */
function debounce(fn, ms) {
  let timer;
  return function(...args) { clearTimeout(timer); timer = setTimeout(() => fn.apply(this, args), ms); };
}

/** Monotonically increasing counter, incremented by showModule() on every navigation.
 *  Each async animation function captures this value at its start and passes it to
 *  sleepOrBail(). If the user navigates to another module mid-animation the epoch
 *  advances, sleepOrBail() rejects, and the animation exits — preventing it from
 *  mutating DOM elements that no longer exist in #module-content. */
let renderEpoch = 0;

/** Sentinel thrown (not an Error instance) by sleepOrBail() when a stale epoch is
 *  detected. Catch with: catch(e) { if (e !== BAIL) throw e; } */
const BAIL = Symbol('bail');

/** Epoch-aware sleep. Resolves normally after ms if the epoch is unchanged; rejects
 *  with BAIL if showModule() was called (epoch advanced) before the timer fired.
 *  Pass the epoch captured at the start of the animation function. */
function sleepOrBail(ms, epoch) {
  return new Promise((resolve, reject) =>
    setTimeout(() => renderEpoch === epoch ? resolve() : reject(BAIL), ms));
}

/** Shorthand for document.getElementById */
function $(id) { return document.getElementById(id); }

