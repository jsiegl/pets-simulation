/* =============================================================================
   2. Tooltip system
   Behaviour:
     • Hover  → show immediately (instant preview)
     • Mouseout → hide unless pinned
     • Click ⓘ → pin open (stays until dismissed)
     • Second click same ⓘ, or click outside → dismiss
   This hybrid hover+pin pattern avoids the "too-narrow target" problem of
   pure hover tooltips while still feeling snappy.
   ============================================================================= */
let ttTarget = null;
let ttPinned = false; // true after user clicks a trigger

function showTooltip(keyOrEl, el) {
  let term, body, targetEl;
  if (typeof keyOrEl === 'string') {
    // Standard lookup: showTooltip('tips-key', element)
    const data = TIPS[keyOrEl];
    if (!data) return;
    term = data.term; body = data.body; targetEl = el;
  } else {
    // Inline: showTooltip(element) — reads data-tip-body / data-tip-term attributes
    targetEl = keyOrEl;
    term = targetEl.dataset.tipTerm || '';
    body = targetEl.dataset.tipBody || '';
    if (!body) return;
  }
  const tt = document.getElementById('tt');
  document.getElementById('tt-term').textContent = term;
  document.getElementById('tt-body').textContent = body;

  // Position: centred above the trigger; flip below if too close to viewport top
  const rect = targetEl.getBoundingClientRect();
  const ttW = 300, ttH = 120;
  let left = rect.left + rect.width / 2 - ttW / 2;
  let top  = rect.top - ttH - 10;
  if (top < 8)                            top  = rect.bottom + 8;
  if (left < 8)                           left = 8;
  if (left + ttW > window.innerWidth - 8) left = window.innerWidth - ttW - 8;

  tt.style.left = left + 'px';
  tt.style.top  = top  + 'px';
  tt.classList.add('show');
  ttTarget = targetEl;
}

// hideTooltip: only hides if not pinned, unless force=true (e.g. module switch)
function hideTooltip(force = false) {
  if (ttPinned && !force) return;
  const tt = document.getElementById('tt');
  tt.classList.remove('show', 'pinned');
  ttPinned = false;
  ttTarget = null;
  document.querySelectorAll('.tip-lbl.pinned').forEach(el => el.classList.remove('pinned'));
}

// Hover: show on mouseover any [data-tip] or [data-tip-body] element
document.addEventListener('mouseover', e => {
  const trigger = e.target.closest('[data-tip]') || e.target.closest('[data-tip-body]');
  if (trigger && !ttPinned) {
    trigger.dataset.tip ? showTooltip(trigger.dataset.tip, trigger) : showTooltip(trigger);
  }
});

// Hide when cursor leaves the trigger entirely (not just moving to a child element)
document.addEventListener('mouseout', e => {
  const trigger = e.target.closest('[data-tip]') || e.target.closest('[data-tip-body]');
  if (trigger && !ttPinned) {
    if (!trigger.contains(e.relatedTarget)) hideTooltip();
  }
});

// Click: pin open on first click; unpin on second click of same trigger
document.addEventListener('click', e => {
  const trigger = e.target.closest('[data-tip]') || e.target.closest('[data-tip-body]');
  if (trigger) {
    e.stopPropagation();
    if (ttPinned && ttTarget === trigger) {
      hideTooltip(true); // second click on same ⓘ → dismiss
    } else {
      document.querySelectorAll('.tip-lbl.pinned').forEach(el => el.classList.remove('pinned'));
      trigger.classList.add('pinned');
      trigger.dataset.tip ? showTooltip(trigger.dataset.tip, trigger) : showTooltip(trigger);
      ttPinned = true;
      document.getElementById('tt').classList.add('pinned');
    }
    return;
  }
  // Click anywhere outside the tooltip panel → dismiss
  if (!e.target.closest('#tt')) hideTooltip(true);
});


