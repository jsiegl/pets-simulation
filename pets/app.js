/**
 * showModule — switches the active module.
 * Increments renderEpoch (cancels in-flight animations), nulls all module-level
 * window handlers, fades the content area out, swaps the render function, then
 * fades back in.
 * The `idx` array order must match the nav button order in index.html exactly.
 */
function showModule(name) {
  renderEpoch++;                                     // invalidate any in-flight animation
  MODULE_FNS.forEach(fn => { window[fn] = undefined; }); // clear stale handlers

  document.querySelectorAll('.nav-btn').forEach(b => b.classList.remove('active'));
  const idx = ['dp','pprl','mpc','fl','synth','tee','he','tok','zkp','trad','compare'];
  const btn = document.querySelectorAll('.nav-btn')[idx.indexOf(name)];
  if (btn) btn.classList.add('active');

  const el = $('module-content');
  el.style.opacity = 0;
  setTimeout(() => {
    hideTooltip(true); // force-dismiss any open tooltip on module change
    modules[name]();
    el.style.opacity = 1;
    el.style.transition = 'opacity 0.25s';
  }, 150);
}


