/** Random float in [min, max) */
function rand(min, max) { return Math.random() * (max - min) + min; }

/** Random integer in [min, max] inclusive */
function randInt(min, max) { return Math.floor(rand(min, max + 1)); }

/** Promise-based delay for use in async animation sequences */
function sleep(ms) { return new Promise(r => setTimeout(r, ms)); }

/** Shorthand for document.getElementById */
function $(id) { return document.getElementById(id); }

/**
 * showModule — switches the active module.
 * Fades the content area out, swaps the render function, then fades back in.
 * The `idx` array order must match the nav button order in index.html exactly.
 */
function showModule(name) {
  document.querySelectorAll('.nav-btn').forEach(b => b.classList.remove('active'));
  const idx = ['dp','pprl','mpc','fl','synth','tee','he','tok','trad','compare'];
  const btn = document.querySelectorAll('.nav-btn')[idx.indexOf(name)];
  if (btn) btn.classList.add('active');

  const el = $('module-content');
  el.style.opacity = 0;
  setTimeout(() => {
    hideTooltip(true); // force-dismiss any open tooltip on module change
    modules[name]();
    el.style.opacity = 1;
    el.style.transition = 'opacity 0.25s';
  }, 150);
}


/* =============================================================================
   4. tradeoffs() — property chip row renderer
   Each item in the array is [label, displayedValue, colourClass].
   Labels matching TRADEOFF_TIP_KEYS get a tooltip ⓘ icon automatically.
   Colour classes: 'val-low' (green), 'val-med' (amber), 'val-high' (red)
   ============================================================================= */
const TRADEOFF_TIP_KEYS = {
  'Privacy strength':          'privacy-strength',
  'Data utility':              'data-utility',
  'Data stays local?':         'data-local',
  '3rd party needed?':         'third-party',
  'Implementation complexity': 'impl-complexity',
  'Output type':               'output-type',
};

function tradeoffs(items) {
  return `<div class="tradeoffs">${items.map(([label, val, cls]) => {
    const key = TRADEOFF_TIP_KEYS[label];
    const labelHtml = key ? TIP(key, label) : label;
    return `<div class="tradeoff">
      <div class="tradeoff-label">${labelHtml}</div>
      <div class="tradeoff-val ${cls}">${val}</div>
    </div>`;
  }).join('')}</div>`;
}


