/* =============================================================================
   0. Theme toggle — dark / light mode
   Persists preference in localStorage key "pets-theme".
   Called by the button in index.html.
   ============================================================================= */

function toggleTheme() {
  const isLight = document.body.classList.toggle('light-mode');
  localStorage.setItem('pets-theme', isLight ? 'light' : 'dark');
  document.getElementById('theme-icon').textContent  = isLight ? '☾' : '☀';
  document.getElementById('theme-label').textContent = isLight ? 'Dark' : 'Light';
}

// Apply saved preference on page load (before first paint)
(function applyStoredTheme() {
  if (localStorage.getItem('pets-theme') === 'light') {
    document.body.classList.add('light-mode');
    // Update button state after DOM is ready
    window.addEventListener('DOMContentLoaded', () => {
      const icon  = document.getElementById('theme-icon');
      const label = document.getElementById('theme-label');
      if (icon)  icon.textContent  = '☾';
      if (label) label.textContent = 'Dark';
    });
  }
})();


